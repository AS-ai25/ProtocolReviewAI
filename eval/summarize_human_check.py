"""Count the labeler's answers in the human-check sheets and write the tables (no LLM, no judgement).

    python eval/summarize_human_check.py        -> eval/human_check/HUMAN_CHECK_ROUND2_SUMMARY.md

Sheets (all filled by Ron Levi; the system columns are never edited):
    verified_findings_check_finding_correct.csv   30 verified findings of the full system (row 4), sampled 30 Oct:
                                                  evidence support (filled 4 Nov) + finding correctness (filled 12 Nov)
    verified_findings_check_v17_tools.csv         30 verified findings of the tool-use full system (row 4'), sampled 8 Nov:
                                                  both columns filled 12 Nov
    unmatched_verified_check.csv                  40 verified scientific findings of row 4 that match no blind label,
                                                  classified 12 Nov

The numbers are reviewer classifications by a single annotator who had seen the system's output by then; they are a
second layer next to the blind labels, never a replacement for them (see HUMAN_REVIEW_PRESUBMISSION_AUDIT_REVISED.md).
"""
from __future__ import annotations

import collections
import csv
import io
import math
import sys
from pathlib import Path

HC = Path(__file__).resolve().parent / "human_check"
OUT = HC / "HUMAN_CHECK_ROUND2_SUMMARY.md"
SUPPORT = "supports (yes / partly / no)"
CORRECT = "finding correct regardless of the quote (yes / partly / no / cannot tell)"
TITLES = {"nct01977547": "ABC PICU", "nct04084990": "SAFER", "nct05199324": "INVEST", "nct05698277": "Fetal cardiac", "nct06846736": "ALK pathology"}


def load(name: str) -> list[dict]:
    return list(csv.DictReader(io.StringIO((HC / name).read_bytes().decode("utf-8-sig"))))


def val(r: dict, col: str) -> str:
    return " ".join((r.get(col) or "").split()).lower()


def domain(r: dict) -> str:
    return "administrative" if r["finding_id"].startswith("ADM") else "scientific"


def source(r: dict) -> str:
    return "rule" if "-R" in r["finding_id"] else "llm"


def fisher_two_sided(a: int, b: int, c: int, d: int) -> float:
    """Two-sided Fisher exact test of the 2x2 table [[a, b], [c, d]]."""
    def p(x):
        return math.comb(a + b, x) * math.comb(c + d, a + c - x) / math.comb(a + b + c + d, a + c)
    p0 = p(a)
    return sum(p(x) for x in range(max(0, a + c - (c + d)), min(a + b, a + c) + 1) if p(x) <= p0 + 1e-12)


def counts(rows: list[dict], col: str, keys: list[str]) -> list[int]:
    c = collections.Counter(val(r, col) for r in rows)
    return [c.get(k, 0) for k in keys]


def table(rows: list[dict], col: str, keys: list[str]) -> list[str]:
    md = ["| Subset | n | " + " | ".join(keys) + " |", "|---|---:|" + "---:|" * len(keys)]
    subsets = [("all", rows), ("scientific findings", [r for r in rows if domain(r) == "scientific"]),
               ("administrative findings", [r for r in rows if domain(r) == "administrative"]),
               ("LLM findings", [r for r in rows if source(r) == "llm"]), ("rule findings", [r for r in rows if source(r) == "rule"])]
    subsets += [(f"{TITLES.get(c, c)} (`{c}`)", [r for r in rows if r["case_id"] == c]) for c in sorted({r["case_id"] for r in rows})]
    for name, sub in subsets:
        md.append(f"| {name} | {len(sub)} | " + " | ".join(str(x) for x in counts(sub, col, keys)) + " |")
    return md


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    old = load("verified_findings_check_finding_correct.csv")
    new = load("verified_findings_check_v17_tools.csv")
    unm = load("unmatched_verified_check.csv")
    kcol = next(k for k in unm[0] if k.startswith("classification"))
    sk, ck = ["yes", "partly", "no"], ["yes", "partly", "no", "cannot tell"]
    so, sn = counts(old, SUPPORT, sk), counts(new, SUPPORT, sk)
    co, cn = counts(old, CORRECT, ck), counts(new, CORRECT, ck)
    p_support = fisher_two_sided(so[0] + so[1], so[2], sn[0] + sn[1], sn[2])
    p_correct = fisher_two_sided(co[0] + co[1], co[2] + co[3], cn[0] + cn[1], cn[2] + cn[3])

    md = ["# Human check, round 2 (12 November 2026): counts", "",
          "Generated by `eval/summarize_human_check.py` from the sheets in this folder; counts only. The reading is in "
          "`reports/CP2_SUMMARY.md` section 9, the labeler's caveats in `HUMAN_REVIEW_PRESUBMISSION_AUDIT_REVISED.md`. "
          "Single annotator (Ron Levi), not blind to the system at this stage, no clinical adjudication.", "",
          "## 1. Evidence support: does the cited passage support the finding?", "",
          "| Sample | n | yes | partly | no | yes or partly |", "|---|---:|---:|---:|---:|---:|",
          f"| Row 4, full system (sampled 30 Oct, checked 4 Nov) | {len(old)} | {so[0]} | {so[1]} | {so[2]} | {so[0] + so[1]} ({(so[0] + so[1]) / len(old):.0%}) |",
          f"| Row 4', full system with tool use (sampled 8 Nov, checked 12 Nov) | {len(new)} | {sn[0]} | {sn[1]} | {sn[2]} | {sn[0] + sn[1]} ({(sn[0] + sn[1]) / len(new):.0%}) |", "",
          f"Fisher exact test, two-sided, \"yes or partly\" against \"no\": p = {p_support:.3f}.", "",
          "### Row 4", ""] + table(old, SUPPORT, sk) + ["", "### Row 4'", ""] + table(new, SUPPORT, sk) + ["",
          "## 2. Finding correctness: is the finding itself right, regardless of the quote? (mentor M6)", "",
          "| Sample | n | yes | partly | no | cannot tell | yes or partly |", "|---|---:|---:|---:|---:|---:|---:|",
          f"| Row 4 | {len(old)} | {co[0]} | {co[1]} | {co[2]} | {co[3]} | {co[0] + co[1]} ({(co[0] + co[1]) / len(old):.0%}) |",
          f"| Row 4' | {len(new)} | {cn[0]} | {cn[1]} | {cn[2]} | {cn[3]} | {cn[0] + cn[1]} ({(cn[0] + cn[1]) / len(new):.0%}) |", "",
          f"Fisher exact test, two-sided, \"yes or partly\" against \"no or cannot tell\": p = {p_correct:.3f}.", "",
          "### Row 4", ""] + table(old, CORRECT, ck) + ["", "### Row 4'", ""] + table(new, CORRECT, ck) + [""]

    cross = collections.Counter((val(r, SUPPORT), val(r, CORRECT)) for r in old)
    cross_n = collections.Counter((val(r, SUPPORT), val(r, CORRECT)) for r in new)
    md += ["### Evidence support against correctness (rows: support; columns: correctness)", "",
           "| Support | Row 4: " + " / ".join(ck) + " | Row 4': " + " / ".join(ck) + " |", "|---|---|---|"]
    for s in sk:
        md.append(f"| {s} | " + " / ".join(str(cross.get((s, c), 0)) for c in ck) + " | " + " / ".join(str(cross_n.get((s, c), 0)) for c in ck) + " |")

    kk = ["true but unlabeled", "duplicate of a matched finding", "wrong", "cannot tell"]
    ku = counts(unm, kcol, kk)
    md += ["", "## 3. The 40 verified scientific findings of row 4 that match no blind label (mentor M5)", "",
           "| Classification | n | share |", "|---|---:|---:|"] + [f"| {k} | {n} | {n / len(unm):.0%} |" for k, n in zip(kk, ku)] + ["",
           "| Protocol | " + " | ".join(kk) + " |", "|---|" + "---:|" * len(kk)]
    for c in sorted({r["case_id"] for r in unm}):
        md.append(f"| {TITLES.get(c, c)} (`{c}`) | " + " | ".join(str(x) for x in counts([r for r in unm if r["case_id"] == c], kcol, kk)) + " |")
    by_src = collections.Counter((r["source"], val(r, kcol)) for r in unm)
    md += ["", "By source: " + "; ".join(f"{s} findings: " + ", ".join(f"{by_src.get((s, k), 0)} {k}" for k in kk if by_src.get((s, k))) for s in ("llm", "rule")) + ".", ""]

    ko = {(r["run_id"], r["finding_id"]): r for r in old}
    both = [(u, ko[(u["run_id"], u["finding_id"])]) for u in unm if (u["run_id"], u["finding_id"]) in ko]
    md += [f"### Findings that appear in both the 30-finding sheet of row 4 and the 40-finding sheet ({len(both)})", "",
           "The same annotator judged these twice, with two different questions. Rows where the answers pull apart are the "
           "ones to re-read before quoting either number.", "",
           "| Protocol | Finding | 40-sheet classification | 30-sheet: evidence support | 30-sheet: finding correct |", "|---|---|---|---|---|"]
    for u, o in both:
        md.append(f"| `{u['case_id']}` | `{u['finding_id']}` | {val(u, kcol)} | {val(o, SUPPORT)} | {val(o, CORRECT)} |")
    md.append("")
    OUT.write_text("\n".join(md), encoding="utf-8")
    print(f"support  row 4 {so} -> row 4' {sn}  (yes/partly/no), Fisher p={p_support:.3f}")
    print(f"correct  row 4 {co} -> row 4' {cn}  (yes/partly/no/cannot tell), Fisher p={p_correct:.3f}")
    print(f"unmatched 40: {dict(zip(kk, ku))}; in both sheets: {len(both)}")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
