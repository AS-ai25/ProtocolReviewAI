"""Administrative-gate pass-rate check and rules-only label drafts for the real-protocol set.

    python eval/gate_check.py                 (live ClinicalTrials.gov lookups, no LLM calls)
    python eval/gate_check.py --no-registry   (registry record = not available)

For every `eval/protocols/<case_id>.pdf` the script runs the Rule-Based Baseline (deterministic checks only,
no agents, no LLM) and writes

  * `eval/protocols/GATE_CHECK.md`  - one row per protocol: pages, text size, metadata the parser found, the
    blocking administrative findings, the baseline decision and the scientific / registry rule hits. The
    table is the evidence for running the ablation with the `force_scientific` gate bypass: public registry
    protocols are not committee submission packages, so the administrative gate is expected to fail on
    most of them.
  * `eval/labeled_cases/_drafts/<case_id>.draft.json` - a label file in the `_TEMPLATE.json` format filled
    with the rule findings. These are DRAFTS for the labeler (Ron): every administrative line should be
    confirmed or deleted, and the scientific pass must still be done blind against the PDF. The underscore
    directory is ignored by `eval/ablation.py` / `eval/evaluate.py`, so a draft is never scored by mistake.

The drafts contain only what the deterministic rules found; nothing here comes from an LLM.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from protocol_review.baseline import run_baseline  # noqa: E402

PROTOCOLS = ROOT / "eval" / "protocols"
DRAFTS = ROOT / "eval" / "labeled_cases" / "_drafts"


def _first_evidence(f: dict) -> tuple[int, str]:
    ev = f.get("evidence") or []
    if not ev:
        return 0, ""
    e = ev[0]
    return int(e.get("page") or 0), (e.get("quote") or e.get("text") or "")[:300]


def _draft(case_id: str, nct: str, res: dict, pages: int) -> dict:
    meta = res["protocol_meta"]
    findings = []
    for f in res["findings"]:
        page, quote = _first_evidence(f)
        findings.append({
            "domain": f["domain"], "category": f["category"], "guideline_ref": f.get("guideline_ref", ""),
            "page": page, "quote": quote, "severity": f["severity"],
            "note": f"[rule draft] {f.get('title', '')}: {f.get('description', '')}".strip(),
        })
    return {
        "_draft": "Rules-only draft generated by eval/gate_check.py. NOT a blind label. Confirm or delete every line, "
                  "add the findings a committee member would raise, set blind=true and labeled_on, then move the file "
                  "one directory up as <case_id>.json BEFORE any LLM run on this protocol.",
        "case_id": case_id,
        "pdf": f"eval/protocols/{case_id}.pdf",
        "nct_id": nct,
        "labeler": "Ron Levi",
        "labeled_on": "",
        "blind": False,
        "description": f"{meta.get('title', '')[:120]} | version {meta.get('version') or '?'} | {meta.get('date') or '?'} | "
                       f"{pages} pages | registry phase {((res.get('registry') or {}).get('phase') or '?')}",
        "expected_decision": res["decision"],
        "expected_findings": findings,
    }


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):      # Windows consoles default to cp1252
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--protocols", default=str(PROTOCOLS))
    ap.add_argument("--drafts", default=str(DRAFTS))
    ap.add_argument("--out", default=str(PROTOCOLS / "GATE_CHECK.md"))
    ap.add_argument("--no-registry", action="store_true", help="do not call ClinicalTrials.gov")
    ap.add_argument("--no-drafts", action="store_true", help="only write the table")
    a = ap.parse_args(argv)

    pdfs = sorted(Path(a.protocols).glob("*.pdf"))
    if not pdfs:
        raise SystemExit(f"no PDFs in {a.protocols}")
    registry_fetch = (lambda nct: (_ for _ in ()).throw(RuntimeError("registry disabled"))) if a.no_registry else None
    started = datetime.now()
    rows, summary = [], []
    for pdf in pdfs:
        case_id = pdf.stem
        m = re.match(r"(nct\d{8})", case_id)
        nct = m.group(1).upper() if m else ""
        res = run_baseline(pdf, nct_id=nct, registry_fetch=registry_fetch, run_id=f"gate-{case_id}", write=False)
        meta, reg = res["protocol_meta"], res.get("registry") or {}
        for k in ("title", "version", "date", "principal_investigator", "sponsor"):
            meta[k] = " ".join(str(meta.get(k, "")).split())  # the regexes can span line breaks; keep the table one-line
        admin = [f for f in res["findings"] if f["domain"] == "administrative"]
        blocking = [f for f in admin if f["severity"] != "info"]
        sci = [f for f in res["findings"] if f["domain"] == "scientific"]
        row = {
            "case_id": case_id, "nct_id": nct, "pages": meta["page_count"], "chars": meta["char_count"],
            "likely_scanned": meta["likely_scanned"], "title": meta.get("title", ""), "version": meta.get("version", ""),
            "date": meta.get("date", ""), "pi": meta.get("principal_investigator", ""), "sponsor": meta.get("sponsor", ""),
            "nct_in_text": nct in (meta.get("nct_ids") or []),
            "registry_found": bool(reg.get("found")), "registry_status": reg.get("status", ""),
            "registry_phase": reg.get("phase", ""), "registry_enrollment": reg.get("enrollment"),
            "registry_error": reg.get("error", ""),
            "decision": res["decision"], "score": res.get("score"),
            "blocking_admin": [f"{f['category']}({f['severity'][0]})" for f in blocking],
            "scientific_rules": [f"{f['category']}({f['severity'][0]})" for f in sci],
            "n_findings": len(res["findings"]),
        }
        rows.append(row)
        summary.append(f"{case_id}: {meta['page_count']}p decision={res['decision']} admin={len(blocking)} sci={len(sci)} "
                       f"registry={'ok' if reg.get('found') else reg.get('error', 'n/a')}")
        print(summary[-1])
        if not a.no_drafts:
            Path(a.drafts).mkdir(parents=True, exist_ok=True)
            (Path(a.drafts) / f"{case_id}.draft.json").write_text(
                json.dumps(_draft(case_id, nct, res, meta["page_count"]), indent=2, ensure_ascii=False), encoding="utf-8")

    n = len(rows)
    n_returned = sum(r["decision"] == "RETURNED_ADMIN" for r in rows)
    n_reg = sum(r["registry_found"] for r in rows)
    md = ["# Administrative-gate check on the real-protocol set", "",
          f"Generated {started.strftime('%Y-%m-%d %H:%M')} by `eval/gate_check.py` (deterministic rules only, no LLM"
          + (", registry disabled" if a.no_registry else ", live ClinicalTrials.gov lookups") + ").", "",
          f"**{n} protocols. Administrative gate fails (RETURNED_ADMIN) on {n_returned}/{n} = {100 * n_returned / n:.0f}%.** "
          f"Registry record found for {n_reg}/{n}.", "",
          "Public ClinicalTrials.gov protocol documents are not Helsinki-committee submission packages: they carry no "
          "consent form, insurance statement, investigator CV / signature page or submission letter. The administrative "
          "gate therefore stops almost every one of them before the scientific stage, which is the production behaviour "
          "the charter asks for. For the evaluation the ablation runs with `force_scientific` (charter v1.4, mentor "
          "agreement 2026-10-20) so that the scientific reviewer and critic are measured on every protocol; the decision "
          "column stays RETURNED_ADMIN.", "",
          "## Per protocol", "",
          "| case_id | Pages | Chars | Version / date found | NCT in text | Registry | Decision | Blocking admin findings | Scientific rule hits |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        reg = (f"{r['registry_status']}, phase {r['registry_phase'] or '-'}, n={r['registry_enrollment']}"
               if r["registry_found"] else f"not found ({r['registry_error'] or 'n/a'})")
        md.append(f"| {r['case_id']} | {r['pages']} | {r['chars']:,} | {r['version'] or '-'} / {r['date'] or '-'} | "
                  f"{'yes' if r['nct_in_text'] else 'no'} | {reg} | {r['decision']} | "
                  f"{', '.join(r['blocking_admin']) or '-'} | {', '.join(r['scientific_rules']) or '-'} |")
    md += ["", "Severity in parentheses: c = critical, m = major, n = minor.", "",
           "## Reading the table", "",
           "* `NCT in text = no` means the document itself does not cite its registry number (the id comes from the file "
           "name); the rule MISSING_REGISTRY_ID fires and the registry cross-check uses the id from the file name.",
           "* The scientific rule hits are regex screens, not findings: they are the starting point of the label drafts in "
           "`eval/labeled_cases/_drafts/` and must be confirmed or deleted by the labeler against the PDF.",
           "* Short documents (< 10 pages) are synopsis-level protocols; whether they stay in the evaluation set is the "
           "labeler's call (see SOURCES.md).", ""]
    Path(a.out).write_text("\n".join(md), encoding="utf-8")
    rd = ROOT / "eval" / "results"
    rd.mkdir(parents=True, exist_ok=True)
    (rd / f"gate_check-{started.strftime('%Y%m%d-%H%M%S')}.json").write_text(
        json.dumps({"generated": started.isoformat(timespec="seconds"), "rows": rows}, indent=1, default=str), encoding="utf-8")
    print(f"\n{n_returned}/{n} RETURNED_ADMIN; wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
